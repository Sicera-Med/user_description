def load_tests(path):
    """Тесты — JSON-список (в .json или в блоке ```json внутри .md)."""
    text = open(path, encoding="utf-8").read()
    if path.endswith(".md"):
        blocks = re.findall(r"```(?:json)?\s*\n(.*?)```", text, re.S)
        text = blocks[0] if blocks else text
    text = re.sub(r",\s*\]", "]", text.strip().rstrip(","))  # висячие запятые
    return json.loads(text)


def build_input(t):
    tpl = find_template(t["study_type"])
    parts = [f"Тип исследования: {tpl['label'] if tpl else t['study_type']}"]
    if t.get("description"):
        parts.append(f"Описание:\n{t['description']}")
    if t.get("conclusion"):
        parts.append(f"Заключение:\n{t['conclusion']}")
    return "\n\n".join(parts)


def system_prompt_for(study_type):
    """Общий промт + только шаблон нужного типа исследования."""
    return SYSTEM_PROMPT + "\n\n" + render_template(study_type)


def ask(model, t):
    resp = client.chat_completion(
        model=model,
        messages=[
            {"role": "system", "content": system_prompt_for(t["study_type"])},
            {"role": "user", "content": build_input(t)},
        ],
        max_tokens=4096,  # рассуждающим MoE-моделям нужен запас
        temperature=0.2,
    )
    return resp.choices[0].message.content or ""  # при нехватке токенов content бывает None


def parse_json(raw):
    raw = re.sub(r"<think>.*?</think>", "", raw, flags=re.S)  # рассуждения reasoning-моделей
    m = re.search(r"\{.*\}", raw, re.S)
    try:
        return json.loads(m.group(0)) if m else None
    except json.JSONDecodeError:
        return None


def main(tests_path="tests.md"):
    tests = load_tests(tests_path)
    results = []
    for model in MODELS:
        for t in tests:
            start = time.time()
            try:
                raw = ask(model, t)
            except Exception as e:
                raw = f"ERROR: {e}"
            parsed = parse_json(raw)
            results.append({
                "model": model,
                "id": t["id"],
                "raw": raw,
                "parsed": parsed,
                "valid_json": parsed is not None,
                "sec": round(time.time() - start, 2),
            })
            print(f"[{model}] {t['id']}: json={'ok' if parsed else 'FAIL'} {results[-1]['sec']}s")

    out = f"results_{time.strftime('%Y%m%d_%H%M%S')}.json"  # не затирать прошлые прогоны
    with open(out, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print(f"Результаты: {out}")


if __name__ == "__main__":
    main(*sys.argv[1:])
